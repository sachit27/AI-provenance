"""Step 5: RESULTS.md + CSVs."""
from __future__ import annotations
import argparse
import json

import numpy as np
import pandas as pd

import common as C
from stats import cohen_kappa, wilson, COVER_LABELS

LABELS = ["MISSED", "COVERED", "STANCE_MISMATCH", "UNCERTAIN", "RELOCATED"]
GUARD = """**Interpretation guardrails.** "Missed" here is an *operational* definition: an idea that recurs among >=10 distinct respondents
(after LLM claim extraction and within-stance clustering) that BOTH an NLI judge (DeBERTa-v3-large, different model family) and an LLM judge
(gpt-4o-mini) find absent from the summary. It is not a human gold standard. Extraction, clustering and canonical wording involve gpt-4o-mini
and embedding choices; the detector is validated only against planted (synthetic) omissions, inclusions and stance flips, whose difficulty
may differ from real cases. UNCERTAIN ideas (judges disagree) are excluded from "missed" counts. Summaries are brief by design, so a high
missed share partly reflects compression, not error; "structural" omissions (missed by every summariser) are the most informative."""


def md(df, floatfmt="{:.1f}"):
    if df is None or len(df) == 0:
        return "_none_\n"
    df = df.copy()
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for v in r.values:
            if isinstance(v, (float, np.floating)):
                cells.append(floatfmt.format(v) if np.isfinite(v) else "")
            else:
                cells.append(str(v).replace("|", "/").replace("\n", " "))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def final_labels(jd, ideas):
    """Add RELOCATED (Scotland: MISSED in official target but COVERED in wider findings)."""
    jd = jd[jd.summary != "official_wider"].copy()
    return jd


def relocated_ids(j_all):
    w = j_all[j_all.summary == "official_wider"]
    return set(w[w.label == "COVERED"].idea_id)


def load(topic, thr):
    d = C.topic_dir(topic)
    ip, jp = d / f"ideas_{C.tag_for(thr)}.parquet", d / f"judgments_{C.tag_for(thr)}.parquet"
    if not (ip.exists() and jp.exists()):
        return None, None, set()
    ideas, j = pd.read_parquet(ip), pd.read_parquet(jp)
    reloc = relocated_ids(j)
    j = j[j.summary != "official_wider"].copy()
    j["final"] = j.label
    m = (j.summary == "official") & (j.label == "MISSED") & j.idea_id.isin(reloc)
    j.loc[m, "final"] = "RELOCATED"
    return ideas, j, reloc


def shares(df, w=None):
    out = {}
    n = len(df)
    for l in LABELS:
        out[f"%{l}"] = 100 * (df.final == l).mean() if n else np.nan
    for l in LABELS:
        out[f"w%{l}"] = 100 * df.n_resp[df.final == l].sum() / df.n_resp.sum() if n else np.nan
    return out


def model_of(s):
    return s if s == "official" else s.split("/")[0]


def run(topics, thr, min_resp, top_n):
    out_dir = C.IA
    parts = [f"# Idea-omission audit: RESULTS\n\nThreshold={thr}, ideas with >={min_resp} distinct respondents (a priori). Generated by `report.py`.\n\n{GUARD}\n"]
    all_rows, val_rows, kappa_rows, sens_rows = [], [], [], []
    for t in topics:
        ideas, j, reloc = load(t, thr)
        if ideas is None:
            print(f"[{t}] no ideas/judgments yet; skipped")
            continue
        j = j.merge(ideas[["idea_id", "stance", "n_resp", "pct_resp", "canonical"]], on="idea_id")
        J = j[j.n_resp >= min_resp].copy()
        nI = J.idea_id.nunique()
        parts.append(f"\n## {t}\n\n{nI} ideas (>= {min_resp} respondents; {len(ideas)} with >=5 before filtering).\n")
        # per summary table
        rows = []
        for s, g in J.groupby("summary"):
            rows.append({"topic": t, "summary": s, "model": model_of(s), "n_ideas": len(g), **shares(g)})
        T = pd.DataFrame(rows)
        all_rows.append(T)
        parts.append("### Share of ideas by label per summary (unweighted %, and respondent-weighted w%)\n\n")
        parts.append(md(T.drop(columns=["model"])))
        if len(T) > 2:
            M = T.groupby("model").agg(n_summaries=("summary", "count"), **{c: (c, "mean") for c in T.columns if c.startswith(("%", "w%"))}).reset_index()
            parts.append("\nMean over seeds, per model:\n\n" + md(M))
        # kappa
        for s, g in J.groupby("summary"):
            kappa_rows.append({"topic": t, "summary": s, "n_pairs": len(g),
                               "kappa_NLI_vs_LLM": cohen_kappa((g.nli_entail >= 0.5).astype(int).tolist(), g.llm.isin(COVER_LABELS).astype(int).tolist()),
                               "pct_agree": 100 * ((g.nli_entail >= 0.5) == g.llm.isin(COVER_LABELS)).mean()})
        # official: prevalence bin and stance
        off = J[J.summary == "official"].copy()
        if len(off):
            off["bin"] = pd.cut(off.n_resp, [0, 9, 19, 49, 10**9], labels=["5-9", "10-19", "20-49", "50+"])
            off["stance_group"] = np.where(off.stance.isin(["oppose", "concern"]), "oppose/concern", off.stance)
            for col, title in (("bin", "prevalence bin (respondents)"), ("stance_group", "stance")):
                tab = off.groupby(col, observed=True).apply(lambda g: pd.Series({"n_ideas": len(g), **shares(g)})).reset_index()
                parts.append(f"\n### Official summary: label shares by {title}\n\n" + md(tab[[col, "n_ideas", "%MISSED", "%COVERED", "%STANCE_MISMATCH", "%UNCERTAIN", "%RELOCATED"]]))
        # structural vs specific
        gen = J[J.summary != "official"]
        if len(gen):
            piv = J.pivot_table(index="idea_id", columns="summary", values="final", aggfunc="first")
            miss = (piv == "MISSED")
            nsum = piv.notna().sum(1)
            nm = miss.sum(1)
            cls = np.where(nm == nsum, "missed by ALL", np.where(nm == 0, "missed by none", "missed by some"))
            meta = ideas.set_index("idea_id").loc[piv.index]
            cs = pd.DataFrame({"class": cls, "n_resp": meta.n_resp.values})
            tab = cs.groupby("class").agg(n_ideas=("n_resp", "size"), respondents=("n_resp", "sum")).reset_index()
            tab["% ideas"] = 100 * tab.n_ideas / tab.n_ideas.sum()
            parts.append(f"\n### Structural vs summariser-specific omissions ({piv.shape[1]} summaries: official + generated)\n\n" + md(tab))
        else:
            piv = J.pivot_table(index="idea_id", columns="summary", values="final", aggfunc="first")
            parts.append("\n_Generated summaries not yet judged: structural-vs-specific split pending._\n")
        # missed ideas csv
        piv = J.pivot_table(index="idea_id", columns="summary", values="final", aggfunc="first")
        nsum = piv.notna().sum(1)
        nmiss = (piv == "MISSED").sum(1)
        meta = ideas.set_index("idea_id")
        mi = meta.loc[piv.index].copy()
        mi["n_summaries_judged"] = nsum
        mi["n_summaries_missing"] = nmiss
        mi["frac_summaries_missing"] = nmiss / nsum
        mi["official_label"] = piv["official"] if "official" in piv else ""
        for c in piv.columns:
            mi[f"label::{c}"] = piv[c]
        o = J[J.summary == "official"].set_index("idea_id")
        for c in ("cos_max", "nli_entail", "nli_contra", "llm", "llm_evidence", "label"):
            mi[f"official_{c}"] = o[c].reindex(mi.index) if len(o) else np.nan
        mi["relocated_to_wider_findings"] = mi.index.isin(reloc)
        qs = mi.quotes.apply(json.loads)
        for k in range(3):
            mi[f"quote{k+1}"] = qs.apply(lambda q: q[k]["quote"] if len(q) > k else "")
            mi[f"quote{k+1}_rid"] = qs.apply(lambda q: q[k]["rid"] if len(q) > k else "")
        mi = mi[(mi.n_resp >= min_resp) & (nmiss > 0)].sort_values("n_resp", ascending=False)
        mi = mi.drop(columns=["quotes", "member_rids", "member_claims"]).rename(columns={"canonical": "canonical_statement"})
        mi.reset_index().to_csv(out_dir / f"missed_ideas_{t}.csv", index=False)
        offm = mi[mi.official_label == "MISSED"].head(top_n)
        parts.append(f"\n### {top_n} most prevalent ideas labeled missed in the official summary\n\n")
        if len(offm):
            tt = offm.reset_index()[["canonical_statement", "stance", "n_resp", "pct_resp", "frac_summaries_missing", "quote1", "quote1_rid"]].copy()
            tt["pct_resp"] = 100 * tt.pct_resp
            tt["quote1"] = tt.quote1.str.slice(0, 160)
            parts.append(md(tt))
        else:
            parts.append("_none_\n")
        if len(piv.columns) > 1:
            allm = mi[mi.frac_summaries_missing == 1].head(top_n)
            parts.append(f"\n### {top_n} most prevalent ideas labeled missed in every summary\n\n" + md(allm.reset_index()[["canonical_statement", "stance", "n_resp", "n_summaries_judged"]]))
        # sensitivity: min respondents
        for m in (5, 10, 20):
            g = j[(j.summary == "official") & (j.n_resp >= m)]
            sens_rows.append({"topic": t, "threshold": thr, "min_resp": m, "n_ideas": len(g), **{f"%{l}": 100 * (g.final == l).mean() if len(g) else np.nan for l in ("MISSED", "COVERED", "STANCE_MISMATCH", "UNCERTAIN", "RELOCATED")}})
        for tt_ in (0.25, 0.30, 0.35):
            if abs(tt_ - thr) < 1e-9:
                continue
            _, j2, _ = load(t, tt_)
            if j2 is not None:
                i2 = pd.read_parquet(C.topic_dir(t) / f"ideas_{C.tag_for(tt_)}.parquet")[["idea_id", "n_resp"]]
                g = j2[j2.summary == "official"].merge(i2, on="idea_id")
                g = g[g.n_resp >= min_resp]
                sens_rows.append({"topic": t, "threshold": tt_, "min_resp": min_resp, "n_ideas": len(g), **{f"%{l}": 100 * (g.final == l).mean() if len(g) else np.nan for l in ("MISSED", "COVERED", "STANCE_MISMATCH", "UNCERTAIN", "RELOCATED")}})
        vp = C.topic_dir(t) / f"validation_{C.tag_for(thr)}.json"
        if vp.exists():
            for test, d in json.loads(vp.read_text()).items():
                for k, v in d.items():
                    if isinstance(v, dict):
                        val_rows.append({"topic": t, "test": test, "judge/rule": k, "k": v["k"], "n": v["n"], "rate %": 100 * v["rate"], "95% Wilson CI": f"[{100*v['ci_lo']:.1f}, {100*v['ci_hi']:.1f}]"})
    if all_rows:
        pd.concat(all_rows).to_csv(out_dir / "summary_shares.csv", index=False)
    if kappa_rows:
        K = pd.DataFrame(kappa_rows)
        K.to_csv(out_dir / "judge_agreement.csv", index=False)
        parts.append("\n## Judge agreement (binary covered vs not; NLI entail>=0.5 vs LLM expressed/partially)\n\n" + md(K, "{:.3f}"))
    if sens_rows:
        S = pd.DataFrame(sens_rows)
        S.to_csv(out_dir / "sensitivity.csv", index=False)
        parts.append("\n## Sensitivity (official summary): minimum respondents and clustering threshold\n\n" + md(S))
    if val_rows:
        V = pd.DataFrame(val_rows)
        V.to_csv(out_dir / "validation_table.csv", index=False)
        parts.append("\n## Validation with planted ground truth\n\n" + md(V))
    (out_dir / "RESULTS.md").write_text("\n".join(parts))
    print("wrote RESULTS.md and CSVs in", out_dir)


def main():
    ap = C.add_common_args(argparse.ArgumentParser(description=__doc__))
    ap.add_argument("--min-resp", type=int, default=10)
    ap.add_argument("--top", type=int, default=10)
    a = ap.parse_args()
    run(a.topics, a.threshold, a.min_resp, a.top)


if __name__ == "__main__":
    main()
